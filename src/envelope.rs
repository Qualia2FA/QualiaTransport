//! The **text envelope** a QR code carries: a byte string becomes text that fits a QR code,
//! and back.
//!
//! # Format (version 1)
//!
//! ```text
//! Q2FA1:<index>/<count>:<BASE32>
//! ```
//!
//! A single frame reads `Q2FA1:1/1:MZXW6` (that string is the RFC 4648 example vector, not
//! any real payload).
//!
//! # Field layout
//!
//! - **The `Q2FA1:` prefix.** What a scanner returns may be anything: somebody else's QR
//!   code, a URL, a business card. The prefix makes "this is not a code of this application"
//!   decidable at a glance, instead of decoding Base32 first and then reporting a "corrupt
//!   payload" — which would send the user in the wrong direction (rescan, when the real
//!   problem is having scanned the wrong code).
//! - **The whole string stays inside the QR alphanumeric mode.** `Q`, `2`, `F`, `A`, `1`,
//!   `:`, `/` and the upper-case letters and digits of Base32 all belong to that
//!   45-character set, so a code uses a single encoding mode. That is precisely why Base32 is
//!   used rather than Base64: the Base32 alphabet is fully contained in the QR alphanumeric
//!   set (those 45 characters), while Base64's lower-case letters are not. See the
//!   documentation of the `base32` module — it is private, hence the code font instead of a
//!   link.
//! - **Index and count come before the Base32.** When one code is not enough, several are
//!   shown in sequence, and the scanning side knows which frames are still missing **without
//!   decoding any payload**. A single frame is written `1/1`; splitting and reassembly live
//!   in [`crate::frame`], and this module only represents.
//! - **No checksum.** The payload itself is authenticated by AEAD at the protocol layer, and
//!   a checksum in the envelope would only invite the misreading "it verified, so it is
//!   genuine". The envelope only **represents**, it does not **authenticate**: it guards
//!   against mistyped characters, not against forgery.
//!
//! The byte mode of a QR code can carry arbitrary bytes, at the cost of **only this crate
//! being able to read them back**: platform cameras (ML Kit, AVFoundation) return strings, a
//! clipboard holds text, and a human copying a code reads text. The text envelope costs about
//! 10% of the capacity and is what every scanner hands back.

use crate::base32;
use crate::error::{Error, Result};

/// Envelope prefix. **Case-sensitive**: it is generated by us and only machines handle it.
const PREFIX: &str = "Q2FA1";

/// Maximum number of frames.
///
/// 255 is well above what is reachable in practice: a frame must hold at least the envelope
/// header (about 10 characters), the smallest QR version 1 already offers 17 alphanumeric
/// characters of capacity, and 255 frames far exceed any usable animated QR sequence
/// (scanning 255 codes in a row is not acceptable behaviour for a user in the first place).
pub const MAX_FRAMES: u32 = 255;

/// Encodes a payload into text a QR code can carry (single frame).
///
/// An empty payload encodes to `Q2FA1:1/1:` — valid per the format, but **meaningless**: no
/// protocol message is empty. Whether to accept it is for the upper layer to decide, the
/// envelope does not decide it on its behalf (see [`decode`]).
#[must_use]
pub fn encode(payload: &[u8]) -> String {
    encode_frame(payload, 1, 1)
}

/// Encodes **one frame** into text a QR code can carry.
///
/// The visibility is `pub(crate)`: the frame index and the frame count are decided by the
/// **splitting** layer ([`crate::frame`]) and are not filled in by callers as they please, and
/// a frame constructed on its own has no legitimate receiver other than the reassembler.
/// Splitting is the only place that produces frames.
///
/// The relation between `index` and `total` (say `index <= total`) is **not** validated here:
/// that is the job of the splitting and reassembly layers, while the envelope only
/// represents. The harm of a duplicated check is that the two rules eventually diverge, and
/// the symptom of divergence is a self-contradictory report like "splitting let it through,
/// reassembly rejects it".
#[must_use]
pub(crate) fn encode_frame(payload: &[u8], index: u32, total: u32) -> String {
    let encoded = base32::encode(payload);
    let mut text = String::with_capacity(PREFIX.len() + 12 + encoded.len());
    text.push_str(PREFIX);
    text.push(':');
    let _ = core::fmt::write(&mut text, format_args!("{index}/{total}:"));
    text.push_str(&encoded);
    text
}

/// Reads the **frame header and payload section** out of QR text, without deciding whether it
/// is single- or multi-frame.
///
/// # The shared base of [`decode`] and [`crate::frame::decode_frame`]
///
/// Both paths do exactly the same first steps (strip the prefix, split the frame header,
/// check the ranges, validate canonicality before Base32); they differ only in **how multiple
/// frames are handled**: the single-frame entry point treats them as "this entry point does
/// not accept them", the multi-frame entry point treats them as normal input. Keeping the
/// common part here stops the two paths from drifting apart.
///
/// # Strictness
///
/// **Leading zeros** (`01/1` is not the canonical spelling), an **out-of-range frame index**
/// (`2/1`) and **a frame count above the limit** are all rejected. The reason is the same as
/// in the Base32 layer: one payload must have exactly one text representation, otherwise
/// there is no answer to "are these two codes the same one", and replay accounting relies on
/// identifier equality.
///
/// # Errors
///
/// - [`Error::NotOurQrText`]: wrong prefix (somebody else's code was scanned).
/// - [`Error::MalformedFrameHeader`]: the prefix matched, but the frame header is invalid.
pub(crate) fn decode_parts(text: &str) -> Result<(u32, u32, &str)> {
    let text = text.trim();
    let rest = text.strip_prefix(PREFIX).ok_or(Error::NotOurQrText)?;
    let rest = rest.strip_prefix(':').ok_or(Error::NotOurQrText)?;
    let (header, body) = rest.split_once(':').ok_or(Error::MalformedFrameHeader)?;
    let (index, count) = header.split_once('/').ok_or(Error::MalformedFrameHeader)?;
    let index = parse_decimal(index).ok_or(Error::MalformedFrameHeader)?;
    let count = parse_decimal(count).ok_or(Error::MalformedFrameHeader)?;

    if count == 0 || count > MAX_FRAMES || index == 0 || index > count {
        return Err(Error::MalformedFrameHeader);
    }
    Ok((index, count, body))
}

/// Decodes QR text back into a payload (**single frames only**).
///
/// # Tolerance and strictness
///
/// Tolerant: leading and trailing whitespace. Some scanners append a newline, and that is not
/// something the user controls.
///
/// Strict: leading zeros, an out-of-range frame index, and every non-canonical spelling of
/// Base32 (see the "Field layout" section of the module documentation and the notes on
/// `decode_parts` — the latter is a private item of this crate, hence the code font).
///
/// # Errors
///
/// - [`Error::NotOurQrText`]: wrong prefix (somebody else's code was scanned).
/// - [`Error::MalformedFrameHeader`]: the prefix matched, but the frame header is invalid.
/// - [`Error::MultiFrameUnsupported`]: the code has multiple frames, and this entry point
///   accepts single frames only.
/// - [`Error::MalformedBase32`]: the Base32 payload is invalid.
pub fn decode(text: &str) -> Result<Vec<u8>> {
    let (index, count, body) = decode_parts(text)?;
    if count > 1 {
        debug_assert!(
            index <= count,
            "frame header consistency is guaranteed by decode_parts"
        );
        return Err(Error::MultiFrameUnsupported { count });
    }
    base32::decode(body)
}

/// Parses one decimal field: non-empty, no leading zeros, all digits, at most 9 digits.
///
/// The 9-digit limit exists **so that rejecting input does not rely on overflow**: a `u32`
/// has at most 10 decimal digits, both fields of this format are far below that, and
/// truncating at 9 leaves ample headroom while rejecting an over-long number before it is
/// parsed.
fn parse_decimal(text: &str) -> Option<u32> {
    if text.is_empty() || text.len() > 9 || text.starts_with('0') {
        return None;
    }
    if !text.bytes().all(|byte| byte.is_ascii_digit()) {
        return None;
    }
    text.parse().ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The format must be pinned byte for byte.
    ///
    /// The expected text is deliberately **written out by hand** rather than cross-checking
    /// [`encode`] against [`decode`]: the latter only proves that encoding and decoding agree
    /// with each other and is completely blind to both being wrong together — while a wire
    /// format cannot be changed once it has been sent out.
    #[test]
    fn wire_format_is_pinned() {
        assert_eq!(encode(b"foo"), "Q2FA1:1/1:MZXW6");
        assert_eq!(encode(b"foobar"), "Q2FA1:1/1:MZXW6YTBOI");
        assert_eq!(encode(b"f"), "Q2FA1:1/1:MY");
        assert_eq!(encode(b""), "Q2FA1:1/1:");
        assert_eq!(
            decode("Q2FA1:1/1:MZXW6").expect("canonical spelling"),
            b"foo"
        );
    }

    #[test]
    fn round_trips_arbitrary_bytes() {
        for len in [0_usize, 1, 5, 6, 31, 64, 255, 1024] {
            let payload: Vec<u8> = (0..len).map(|i| (i * 37 % 256) as u8).collect();
            let text = encode(&payload);
            assert_eq!(
                decode(&text).expect("a self-encoded payload must decode"),
                payload
            );
        }
    }

    /// Somebody else's QR code must be reported as "not our code", not as "corrupt payload".
    #[test]
    fn other_peoples_codes_are_recognized_as_foreign() {
        for text in [
            "",
            "https://example.com",
            "otpauth://totp/a?secret=JBSWY3DPEHPK3PXP",
            "Q2FA",
            "Q2FA1",
            "q2fa1:1/1:MZXW6",
            "X2FA1:1/1:MZXW6",
        ] {
            let result = decode(text);
            let is_foreign = matches!(result, Err(Error::NotOurQrText));
            assert!(is_foreign, "should report a foreign code, got {result:?}");
        }
    }

    #[test]
    fn malformed_frame_headers_are_rejected() {
        for text in [
            "Q2FA1:1/1",
            "Q2FA1:1:MZXW6",
            "Q2FA1:/1:MZXW6",
            "Q2FA1:1/:MZXW6",
            "Q2FA1:01/1:MY",
            "Q2FA1:1/01:MY",
            "Q2FA1:0/1:MY",
            "Q2FA1:1/0:MY",
            "Q2FA1:2/1:MY",
            "Q2FA1:3/2:MY",
            "Q2FA1:1/256:MY",
            "Q2FA1:1/99999999999:MY",
            "Q2FA1:1/1x:MY",
            "Q2FA1: 1/1:MY",
        ] {
            let result = decode(text);
            let is_malformed = matches!(result, Err(Error::MalformedFrameHeader));
            assert!(
                is_malformed,
                "should report a malformed frame header, got {result:?}"
            );
        }
    }

    /// Multiple frames are a **planned format**, not bad input: they must be reported
    /// separately from an invalid frame header.
    #[test]
    fn multi_frame_is_reported_as_unsupported_not_malformed() {
        let result = decode("Q2FA1:1/2:MZXW6");
        let expected = matches!(result, Err(Error::MultiFrameUnsupported { count: 2 }));
        assert!(expected, "2 frames must report unsupported, got {result:?}");

        let result = decode("Q2FA1:255/255:MY");
        let expected = matches!(result, Err(Error::MultiFrameUnsupported { count: 255 }));
        assert!(
            expected,
            "255 frames must be a legal frame header, got {result:?}"
        );
    }

    #[test]
    fn bad_base32_is_reported_as_such() {
        for text in [
            "Q2FA1:1/1:M0",
            "Q2FA1:1/1:M",
            "Q2FA1:1/1:MZ",
            "Q2FA1:1/1:MZ:W6",
        ] {
            let result = decode(text);
            let is_base32 = matches!(result, Err(Error::MalformedBase32));
            assert!(
                is_base32,
                "should report a bad Base32 payload, got {result:?}"
            );
        }
    }

    /// A newline added by the scanner must not show the user "this is not our code".
    #[test]
    fn surrounding_whitespace_is_tolerated() {
        assert_eq!(
            decode("  Q2FA1:1/1:MZXW6\n").expect("whitespace is tolerated"),
            b"foo"
        );
        assert_eq!(
            decode("\tQ2FA1:1/1:MY ").expect("whitespace is tolerated"),
            b"f"
        );
    }
}
